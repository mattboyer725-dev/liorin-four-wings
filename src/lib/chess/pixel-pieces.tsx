export function PixelPiece({
  piece,
  color,
  className,
}: {
  piece: PieceSymbol;
  color: "w" | "b";
  className?: string;
}) {
  const rows = MAPS[piece];
  const fill = color === "w" ? "var(--color-piece-w)" : "var(--color-piece-b)";
  const edge = color === "w" ? "var(--color-bg)" : "var(--color-primary)";
  const cells: ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      const outline =
        rows[y - 1]?.[x] !== "#" ||
        rows[y + 1]?.[x] !== "#" ||
        row[x - 1] !== "#" ||
        row[x + 1] !== "#";
      cells.push(
        <rect
          key={`${x}-${y}`}
          x={x}
          y={y}
          width={1}
          height={1}
          fill={outline ? edge : fill}
        />,
      );
    }
  });
  return (
    <svg
      viewBox="0 0 12 12"
      className={className}
      aria-hidden="true"
      shapeRendering="crispEdges"
    >
      {cells}
    </svg>
  );
}
